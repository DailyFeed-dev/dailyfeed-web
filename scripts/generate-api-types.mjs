// 백엔드 Swagger(OpenAPI) 문서로 src/lib/api/schema.d.ts 타입 파일을 다시 만듭니다.
//
// 사용법 1) 파일로 만들기 (권장)
//   Swagger 에 로그인된 브라우저에서 <백엔드주소>/v3/api-docs 를 열어 api-docs.json 으로 저장한 뒤
//   npm run api:types -- ./api-docs.json
//
// 사용법 2) 서버에서 바로 읽기 (API 문서가 로그인 없이 열리는 경우에만)
//   npm run api:types        (.env.local 의 API_PROXY_TARGET 사용)
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import nextEnv from '@next/env';
import openapiTS, { astToString } from 'openapi-typescript';

nextEnv.loadEnvConfig(process.cwd());

const outFile = path.join('src', 'lib', 'api', 'schema.d.ts');
const fileArg = process.argv[2];

let source;
if (fileArg) {
  if (!fs.existsSync(fileArg)) {
    console.error(`❌ 파일을 찾을 수 없습니다: ${fileArg}`);
    process.exit(1);
  }
  source = pathToFileURL(path.resolve(fileArg));
} else {
  const target = process.env.API_PROXY_TARGET;
  if (!target) {
    console.error(
      '❌ API_PROXY_TARGET 이 없습니다. .env.example 을 참고해 .env.local 을 만들어 주세요.',
    );
    process.exit(1);
  }
  source = new URL('/v3/api-docs', target);
}

console.log(`📄 ${source} 에서 API 문서를 읽는 중...`);
try {
  const ast = await openapiTS(source);
  const header =
    '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n';
  fs.writeFileSync(outFile, header + astToString(ast));
  console.log(`✅ ${outFile} 갱신 완료`);
} catch (e) {
  if (String(e).includes('401')) {
    console.error('❌ API 문서가 로그인을 요구합니다 (401).');
    console.error(
      '   브라우저에서 Swagger 에 로그인한 뒤 <백엔드주소>/v3/api-docs 를 api-docs.json 으로 저장하고',
    );
    console.error('   npm run api:types -- ./api-docs.json  으로 실행해 주세요.');
  } else {
    console.error('❌ 타입 생성 실패:', e.message ?? e);
  }
  process.exit(1);
}
